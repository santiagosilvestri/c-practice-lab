/*
    Assignment name  : ft_itoa
    Expected files   : ft_itoa.c
    Allowed functions: malloc
    --------------------------------------------------------------------------------

    Write a function that takes an int and converts it to a null-terminated string.

    The function must return the result in a char array that you must allocate.

    Your function must be declared as follows:

    char	*ft_itoa(int nbr);
*/

#include <stdlib.h>

static int	ft_numlen(int n)
{
	int	len;

	len = 0;
	if (n <= 0)
		len++;
	while (n != 0)
	{
		n = n / 10;
		len++;
	}
	return (len);
}

char	*ft_itoa(int n)
{
	char	*str;
	long	num;
	int		len;

	num = n;
	len = ft_numlen(n);
	str = malloc(sizeof(char) * (len + 1));
	if (!str)
		return (NULL);
	str[len] = '\0';
	if (num == 0)
		str[0] = '0';
	if (num < 0)
	{
		str[0] = '-';
		num = -num;
	}
	while (num > 0)
	{
		len--;
		str[len] = (num % 10) + '0';
		num = num / 10;
	}
	return (str);
}
